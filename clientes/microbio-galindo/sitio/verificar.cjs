const fs=require('node:fs'),path=require('node:path'),vm=require('node:vm'),crypto=require('node:crypto');
const assert=(x,m)=>{if(!x)throw Error(m)};
const ctx={window:{},Date,console,document:{addEventListener(){}}};vm.createContext(ctx);
for(const name of ['config.js','cliente.js','media-manifest.js'])vm.runInContext(fs.readFileSync(path.join(__dirname,name),'utf8'),ctx);
const c=ctx.window.TDN,manifest=ctx.window.CLIENT_MEDIA;
assert(c.pareja.nombreA==='Microbio'&&c.pareja.nombreB==='Galindo','Nombres');
assert(c.pareja.fechaInicio==='2025-01-21','Fecha');
assert(c.acceso.password===crypto.createHash('sha256').update('210125').digest('hex')&&!c.acceso.demo,'Contraseña');
assert(c.notificacion.whatsapp==='526633316789','WhatsApp');
assert(c.temporadas.filter(t=>t.tipo==='pelicula').length===12,'12 películas');
assert(c.temporadas.filter(t=>t.tipo==='serie').length===3,'3 series');
const eps=c.temporadas.flatMap(t=>t.episodios);
assert(eps.length===18&&eps.filter(e=>e.interaccion).length===7,'18 capítulos y 7 juegos');
assert(eps.every(e=>e.escenas.length>=5),'Escenas');
assert(new Set(c.temporadas.map(t=>t.musica)).size===15,'15 canciones diferentes');
assert(manifest.fotos.length===17&&manifest.videos.length===13,'Todos los medios personales');
assert(c.final.carta([]).includes('Si no me respondes, sabré entender')&&c.final.carta([]).includes('juntos hasta viejitos'),'Mensaje original');
const used=new Set();
function walk(x){if(typeof x==='string'&&x.startsWith('assets/'))used.add(x);else if(Array.isArray(x))x.forEach(walk);else if(x&&typeof x==='object')Object.values(x).forEach(walk)}
walk(c);walk(manifest);
for(const src of used)assert(fs.existsSync(path.join(__dirname,src)),`Falta ${src}`);
for(const t of c.temporadas)assert(new Set(t.episodios.flatMap(e=>e.escenas.map(s=>s.img))).size<=10,'Más de 10 medios por título');
const texts=fs.readdirSync(__dirname).filter(n=>/\.(html|js|css)$/.test(n)).map(n=>fs.readFileSync(path.join(__dirname,n),'utf8')).join('\n');
assert(!/Alondra|Adrián|alondra-adrian|ar_auth|ar_v1|Diego|Sofía|Café Palermo|Guadalajara/.test(texts),'Datos ajenos');
assert(texts.includes('mg_v1')&&texts.includes('mg_auth'),'Progreso independiente');
const base=JSON.parse(fs.readFileSync(path.join(__dirname,'../integridad-originales.json'),'utf8'));
const root=path.resolve(__dirname,'../../..');
for(const [name,sha] of Object.entries(base))assert(crypto.createHash('sha256').update(fs.readFileSync(path.join(root,name))).digest('hex')===sha,`Se modificó un original: ${name}`);
console.log(`OK: 12 películas, 3 series, 18 capítulos, 7 juegos, 15 canciones, 17 fotos, 13 videos; ${used.size} rutas válidas. ${Object.keys(base).length} archivos previos intactos.`);
